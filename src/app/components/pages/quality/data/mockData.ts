// Violation heatmap (hour x zone for manager view)
export const VIOLATION_HEATMAP: { hour: number; zone: string; value: number }[] = [];
const ZONES_HM = ["Zone A", "Zone B", "Zone C", "Zone D", "Zone E", "Zone F"];
